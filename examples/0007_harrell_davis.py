"""Harrell–Davis with high-precision beta interval probabilities.

Optional Python dependency: python3 -m pip install mpmath
HTML lessons use precomputed weights and require no installation.

python3 examples/0007_harrell_davis.py --p .5 --values 1 2 3 4 100
python3 examples/0007_harrell_davis.py --simulate clean
python3 examples/0007_harrell_davis.py --simulate wide
python3 examples/0007_harrell_davis.py --export-js > assets/hd-weights.js
"""
import argparse
import json
import math
import sys
sys.dont_write_bytecode = True
try:
    import mpmath as mp
except ImportError:
    raise SystemExit("Python example needs mpmath: python3 -m pip install mpmath")
from statistics import mean, median
from sampling_helpers import mulberry32, normal_generator, quantile_details


from harrell_davis_helpers import hd_weights, estimate, moments


def simulate(scenario, seed=43, repetitions=2000):
    if scenario not in ('clean', 'wide') or not isinstance(seed, int) or not 0 <= seed <= 4294967295 or not 1 <= repetitions <= 10000:
        raise ValueError("Invalid Monte Carlo settings")
    rng = mulberry32(seed)
    normal = normal_generator(rng)
    weights = [float(w) for w in hd_weights(5, .5)]
    results = dict(type7=[], hd=[])
    for _ in range(repetitions):
        sample = []
        for _ in range(5):
            rare = next(rng) < .02
            value = next(normal)
            sample.append(value * (100 if scenario == 'wide' and rare else 1))
        ordered = sorted(sample)
        results['type7'].append(median(ordered))
        results['hd'].append(sum(w * x for w, x in zip(weights, ordered)))
    return dict(n=5, p=.5, target=0, seed=seed, repetitions=repetitions, scenario=scenario,
                type7=moments(results['type7'], 0), hd=moments(results['hd'], 0))


def export_js():
    data = {str(n): {str(p): [float(w) for w in hd_weights(n, p)] for p in (.1, .5, .9)} for n in (5, 9, 19)}
    return ('/* Generated by examples/0007_harrell_davis.py --export-js; mpmath 1.3.0, 80 digits. */\n'
            '(function(root){"use strict";const weights=' + json.dumps(data, separators=(',', ':')) +
            ';Object.values(weights).forEach(row=>{Object.values(row).forEach(Object.freeze);Object.freeze(row);});'
            'root.CourseHDWeights=Object.freeze(weights);'
            'if(typeof module!=="undefined"&&module.exports)module.exports=root.CourseHDWeights;'
            '}(typeof globalThis!=="undefined"?globalThis:this));\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--p', type=float, default=.5)
    parser.add_argument('--values', type=float, nargs='+', default=[1, 2, 3, 4, 5])
    parser.add_argument('--simulate', choices=('clean', 'wide'))
    parser.add_argument('--seed', type=int, default=43)
    parser.add_argument('--repetitions', type=int, default=2000)
    parser.add_argument('--export-js', action='store_true')
    args = parser.parse_args()
    try:
        if args.export_js:
            print(export_js(), end='')
        elif args.simulate:
            print(json.dumps(simulate(args.simulate, args.seed, args.repetitions), indent=2))
        else:
            result, weights = estimate(args.values, args.p)
            print(json.dumps(dict(n=len(args.values), p=args.p, hd=mp.nstr(result, 17),
                                  type7=quantile_details(args.values, args.p, 7)['value'],
                                  weights=[mp.nstr(w, 17) for w in weights]), indent=2))
    except (ValueError, ArithmeticError) as error:
        parser.error(str(error))
